export function getCourseById(levelId: string): CourseLevelDefinition | undefined {
  return COURSES.find((c) => c.id === levelId);
}

export function getLessonById(lessonId: string): { lesson: LessonExercise; course: CourseLevelDefinition } | undefined {
  for (const course of COURSES) {
    const lesson = course.lessons.find((l) => l.id === lessonId);
    if (lesson) {
      return { lesson, course };
    }
  }
  return undefined;
}
